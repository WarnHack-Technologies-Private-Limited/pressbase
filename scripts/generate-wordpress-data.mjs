#!/usr/bin/env node
/**
 * Regenerates the data Pressbase copies from a WordPress release (GPL-2.0-or-later):
 *
 * - packages/theme-json/src/data/wordpress-theme-json.ts  ← wp-includes/theme.json
 * - packages/theme-json/src/data/core-blocks.ts           ← the style metadata
 *   (supports, selectors, style variations) of every wp-includes/blocks/{name}/block.json
 * - apps/core/src/blocks/wordpress-blocks.ts               ← server metadata of the core
 *   blocks not already listed in apps/core/src/blocks/metadata.ts
 *
 * Usage: node scripts/generate-wordpress-data.mjs ../wordpress
 * Then run `pnpm format`.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const wordpress = path.resolve(process.argv[2] ?? '../wordpress');
const root = path.resolve(import.meta.dirname, '..');
const blocksDir = path.join(wordpress, 'wp-includes/blocks');

const json = (value) => JSON.stringify(value, null, 2);

// 1. Core theme.json.
const themeJson = JSON.parse(readFileSync(path.join(wordpress, 'wp-includes/theme.json'), 'utf8'));
delete themeJson.$schema;
writeFileSync(
  path.join(root, 'packages/theme-json/src/data/wordpress-theme-json.ts'),
  `import type { ThemeJsonData } from '../types';

/**
 * WordPress's own theme.json (wordpress/wp-includes/theme.json, WordPress 7.1.3,
 * GPL-2.0-or-later): the "default" origin every theme is merged onto.
 * Generated by scripts/generate-wordpress-data.mjs; don't edit by hand.
 */
export const WORDPRESS_THEME_JSON: ThemeJsonData = ${json(themeJson)};
`,
);

// 2. Every core block's block.json.
const blocks = [];
for (const dir of readdirSync(blocksDir, { withFileTypes: true })) {
  if (!dir.isDirectory()) continue;
  try {
    blocks.push(JSON.parse(readFileSync(path.join(blocksDir, dir.name, 'block.json'), 'utf8')));
  } catch {
    // Not a block folder.
  }
}
blocks.sort((a, b) => a.name.localeCompare(b.name));
const dynamic = new Set(
  readdirSync(blocksDir)
    .filter((f) => f.endsWith('.php'))
    .map((f) => `core/${f.slice(0, -4)}`)
    .filter((name) => blocks.some((b) => b.name === name)),
);

const styleMetadata = {};
for (const block of blocks) {
  const entry = { supports: block.supports ?? {} };
  if (block.selectors) entry.selectors = block.selectors;
  if (block.styles?.length) entry.styles = block.styles.map((s) => s.name);
  styleMetadata[block.name] = entry;
}
writeFileSync(
  path.join(root, 'packages/theme-json/src/data/core-blocks.ts'),
  `import type { BlockStyleMetadata } from '../types';

/**
 * Style metadata of WordPress's core blocks — \`supports\`, \`selectors\` and
 * style variation names from wordpress/wp-includes/blocks/{name}/block.json
 * (WordPress 7.1.3, GPL-2.0-or-later). WP_Theme_JSON::get_blocks_metadata()
 * derives each block's CSS selectors from these.
 * Generated by scripts/generate-wordpress-data.mjs; don't edit by hand.
 */
export const CORE_BLOCK_STYLE_METADATA: Record<string, BlockStyleMetadata> = ${json(styleMetadata)};
`,
);

// 3. Server metadata for core blocks core doesn't list yet.
const existing = readFileSync(path.join(root, 'apps/core/src/blocks/metadata.ts'), 'utf8');
const keep = [
  'apiVersion',
  'name',
  'title',
  'category',
  'parent',
  'ancestor',
  'allowedBlocks',
  'description',
  'keywords',
  'textdomain',
  'attributes',
  'usesContext',
  'providesContext',
  'supports',
  'selectors',
  'styles',
];
const server = {};
for (const block of blocks) {
  if (existing.includes(`'${block.name}': {`)) continue;
  const entry = {};
  for (const key of keep) if (block[key] !== undefined) entry[key] = block[key];
  // `rich-text` attributes hold HTML strings (WP_Block_Type treats them as strings).
  for (const attribute of Object.values(entry.attributes ?? {})) {
    if (attribute.type === 'rich-text') attribute.type = 'string';
  }
  server[block.name] = entry;
}
writeFileSync(
  path.join(root, 'apps/core/src/blocks/wordpress-blocks.ts'),
  `import type { BlockTypeArgs } from '@pressbase/blocks';

/**
 * block.json metadata of every other WordPress core block (WordPress 7.1.3,
 * wordpress/wp-includes/blocks/{name}/block.json, GPL-2.0-or-later). WordPress
 * registers all core blocks on the server; Pressbase does too, so block
 * supports (layout, spacing…) apply to static blocks such as Group and
 * Columns when templates render, and so the block-types endpoint is complete.
 * Generated by scripts/generate-wordpress-data.mjs; don't edit by hand.
 */
export const WORDPRESS_BLOCK_METADATA: Record<string, BlockTypeArgs & { name: string }> = ${json(server)};

/** Core blocks WordPress renders on the server (those with a PHP file in wp-includes/blocks/). */
export const WORDPRESS_DYNAMIC_BLOCKS: ReadonlySet<string> = new Set(${json([...dynamic].sort())});
`,
);
console.log(`Wrote metadata for ${blocks.length} blocks.`);
