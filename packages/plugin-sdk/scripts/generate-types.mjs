// Generates src/core.generated.d.ts: core's plugin-facing types
// (apps/core/src/plugins/sdk-types.ts and everything they reference) bundled
// into one declaration file. Workspace packages (@pressbase/hooks, db,
// blocks…) are inlined; third-party packages (hono, drizzle-orm, zod) stay
// imports, satisfied by this package's dependencies. Types only: nothing of
// core's runtime reaches a plugin's bundle.
//
// Hook registries are interfaces that core's modules extend with
// `declare module '@pressbase/hooks' { … }`. Once @pressbase/hooks is inlined
// those blocks would augment a module plugin authors don't have, so they are
// unwrapped into top-level declarations, which merge with the inlined
// FilterRegistry and ActionRegistry in the same file.

import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { rollup } from 'rollup';
import { dts } from 'rollup-plugin-dts';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../../..');
const core = path.join(root, 'apps/core');
const entry = path.join(core, 'src/plugins/sdk-types.ts');
const output = path.join(here, '../src/core.generated.d.ts');
const AUGMENT = "declare module '@pressbase/hooks' {";

/** Every module that extends the hook registries must be part of the entry. */
async function checkRegistries() {
  const entryText = await readFile(entry, 'utf8');
  const missing = [];
  const walk = async (dir) => {
    for (const item of await readdir(dir, { withFileTypes: true })) {
      const full = path.join(dir, item.name);
      if (item.isDirectory()) {
        if (item.name !== 'node_modules' && item.name !== 'dist') await walk(full);
      } else if (/\.ts$/.test(item.name) && !/\.(test|d)\.ts$/.test(item.name)) {
        const text = await readFile(full, 'utf8');
        if (!text.split('\n').some((line) => line.startsWith(AUGMENT))) continue;
        const rel = path.relative(root, full).split(path.sep).join('/');
        if (rel.startsWith('packages/hooks/')) continue;
        let specifier;
        if (rel.startsWith('packages/')) specifier = `@pressbase/${rel.split('/')[1]}`;
        else {
          specifier = path
            .relative(path.dirname(entry), full)
            .split(path.sep)
            .join('/')
            .replace(/\.ts$/, '');
          if (!specifier.startsWith('.')) specifier = `./${specifier}`;
        }
        if (!entryText.includes(`'${specifier}'`)) missing.push(`${rel} (${specifier})`);
      }
    }
  };
  await walk(path.join(core, 'src'));
  await walk(path.join(root, 'packages'));
  if (missing.length) {
    throw new Error(
      `These modules add hooks but aren't imported by ${path.relative(root, entry)}:\n  ${missing.join('\n  ')}`,
    );
  }
}

/** Replaces each `declare module '@pressbase/hooks' { … }` block with its body. */
function unwrapAugmentations(code) {
  let out = '';
  let index = 0;
  for (;;) {
    const start = code.indexOf(AUGMENT, index);
    if (start < 0) return out + code.slice(index);
    out += code.slice(index, start);
    let depth = 0;
    let end = start + AUGMENT.length - 1;
    for (; end < code.length; end++) {
      if (code[end] === '{') depth++;
      else if (code[end] === '}' && --depth === 0) break;
    }
    out += code
      .slice(start + AUGMENT.length, end)
      .replace(/^\n/, '')
      .replace(/^ {4}/gm, '');
    index = end + 1;
  }
}

await checkRegistries();
// rollup-plugin-dts resolves `types: ["node"]` from the working directory.
process.chdir(core);
const bundle = await rollup({
  input: entry,
  external: (id) => !id.startsWith('.') && !path.isAbsolute(id) && !id.startsWith('@pressbase/'),
  plugins: [
    {
      name: 'pressbase-workspace',
      resolveId: (id) =>
        id.startsWith('@pressbase/')
          ? path.join(root, 'packages', id.slice('@pressbase/'.length), 'src/index.ts')
          : null,
    },
    dts({ tsconfig: path.join(core, 'tsconfig.json'), respectExternal: true }),
  ],
});
const { output: chunks } = await bundle.generate({ format: 'es' });
await bundle.close();
const code = unwrapAugmentations(chunks[0].code);
if (code.includes("declare module '@pressbase/")) {
  throw new Error('A module augmentation was left in the generated types.');
}
await writeFile(
  output,
  `// Generated by scripts/generate-types.mjs from apps/core/src/plugins/sdk-types.ts. Do not edit.\n${code}`,
);
console.log(`Wrote ${path.relative(root, output)} (${code.split('\n').length} lines).`);
