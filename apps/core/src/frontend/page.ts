import { AsyncLocalStorage } from 'node:async_hooks';
import type { CurrentUser } from '../auth/users';
import type { ActiveTheme } from '../themes/service';
import type { Scripts, Styles } from './dependencies';
import type { MainQuery } from './query';

/**
 * The state of one public page render — what WordPress keeps in globals
 * while it renders a request ($wp_query, the style engine's block-supports
 * store, wp_unique_id()'s counter, the template part recursion guard).
 *
 * It travels with the render through AsyncLocalStorage, so block render
 * callbacks and render filters can reach it without new parameters. Outside
 * a page render (REST previews), `currentPage()` is undefined.
 */
export class PageRender {
  /** CSS generated by block supports (the `core-block-supports` inline style). */
  readonly supportStyles: string[] = [];
  /** CSS for block style variation instances (`block-style-variation-styles`). */
  readonly variationStyles: string[] = [];
  /** Inline scripts the page needs (the navigation menu toggle), printed in `wp_footer`. */
  readonly inlineScripts = new Set<string>();
  /**
   * This page's scripts and styles (WP_Scripts / WP_Styles): a copy of the
   * site-wide registrations that `kernel.scripts` and `kernel.styles` change
   * while the page renders. Set by the renderer.
   */
  scripts: Scripts | undefined;
  styles: Styles | undefined;
  /** The id the skip link points to, once the template has rendered. */
  skipLinkTarget: string | undefined;
  #ids = new Map<string, number>();

  constructor(
    readonly theme: ActiveTheme,
    readonly main: MainQuery,
    readonly user: CurrentUser | null,
    readonly home: string,
    /** The request's path and query string, e.g. `/2026/10/hello/?replytocom=2`. */
    readonly path = '/',
    /** The request's cookies (post passwords). */
    readonly cookies: Map<string, string> = new Map(),
  ) {}

  /** wp_unique_id( $prefix ) / wp_unique_prefixed_id(). */
  uniqueId(prefix = ''): string {
    const next = (this.#ids.get(prefix) ?? 0) + 1;
    this.#ids.set(prefix, next);
    return `${prefix}${next}`;
  }

  addSupportStyle(css: string): void {
    if (css && !this.supportStyles.includes(css)) this.supportStyles.push(css);
  }
}

const storage = new AsyncLocalStorage<PageRender>();

export function currentPage(): PageRender | undefined {
  return storage.getStore();
}

export function withPage<T>(page: PageRender, fn: () => Promise<T>): Promise<T> {
  return storage.run(page, fn);
}
